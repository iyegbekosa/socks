import pytest
from django.contrib.auth import authenticate
from django.core.exceptions import ValidationError
from django.db import IntegrityError, transaction
from django_tenants.utils import schema_context

from apps.accounts.services import create_student_user
from tests.accounts.factories import DEFAULT_PASSWORD, StaffFactory, StudentFactory

pytestmark = pytest.mark.django_db


def test_username_autogenerated(school_a):
    with schema_context("school_a"):
        u = StaffFactory()
        assert u.username.startswith("u_") and len(u.username) == 14


def test_argon2(school_a):
    with schema_context("school_a"):
        assert StaffFactory().password.startswith("argon2$")


def test_staff_phone_login_any_format(school_a):
    with schema_context("school_a"):
        u = StaffFactory(phone="0803 123 4567")
        assert u.phone == "+2348031234567"
        assert authenticate(identifier="+2348031234567", password=DEFAULT_PASSWORD) == u
        assert authenticate(identifier="08031234567", password=DEFAULT_PASSWORD) == u


def test_email_login_case_insensitive(school_a):
    with schema_context("school_a"):
        u = StaffFactory(email="ada@school.ng")
        assert authenticate(identifier="Ada@School.NG", password=DEFAULT_PASSWORD) == u


def test_student_login_loose_admission(school_a):
    with schema_context("school_a"):
        s = StudentFactory(admission_number="GFS/2026/0042")
        assert authenticate(identifier=" gfs/2026/0042 ", password=DEFAULT_PASSWORD) == s


def test_student_cannot_login_by_recovery_phone(school_a):
    with schema_context("school_a"):
        StudentFactory(recovery_phone="0803 123 4567")
        assert authenticate(identifier="+2348031234567", password=DEFAULT_PASSWORD) is None


def test_staff_cannot_login_by_admission_number(school_a):
    with schema_context("school_a"):
        StaffFactory(admission_number="GFS/2026/0001")
        assert authenticate(identifier="GFS/2026/0001", password=DEFAULT_PASSWORD) is None


def test_wrong_password_and_inactive(school_a):
    with schema_context("school_a"):
        u = StaffFactory(email="x@school.ng")
        assert authenticate(identifier="x@school.ng", password="nope") is None
        u.is_active = False
        u.save()
        assert authenticate(identifier="x@school.ng", password=DEFAULT_PASSWORD) is None


def test_blank_email_allowed_twice_duplicate_not(school_a):
    with schema_context("school_a"):
        StaffFactory(email="", phone="+2348031110001")
        StaffFactory(email="", phone="+2348031110002")
        StaffFactory(email="a@b.ng")
        with pytest.raises(IntegrityError), transaction.atomic():
            StaffFactory(email="a@b.ng")


def test_invalid_phone_full_clean(school_a):
    with schema_context("school_a"):
        u = StaffFactory.build(phone="12345")
        with pytest.raises(ValidationError):
            u.full_clean()


def test_create_student_user(school_a):
    with schema_context("school_a"):
        s = create_student_user(
            admission_number=" gfs/2026/0777 ",
            full_name="Ada Obi Eze",
            recovery_phone="0803 123 4567",
            password=DEFAULT_PASSWORD,
        )
        assert s.kind == "student" and s.admission_number == "GFS/2026/0777"
        assert s.recovery_phone == "+2348031234567"
        assert s.first_name == "Ada" and s.last_name == "Obi Eze"
        assert s.password.startswith("argon2$")
